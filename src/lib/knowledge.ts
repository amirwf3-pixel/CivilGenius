/* ----------------------------------------------------------- local engine -- */

const STOPWORDS = new Set(['و', 'در', 'به', 'از', 'که', 'این', 'آن', 'یک', 'است', 'را', 'با', 'های', 'برای', 'چه', 'چگونه', 'می', 'کند', 'کنم', 'the', 'a', 'is', 'of', 'to', 'and']);

/** Persian/Arabic normalisation + ZWNJ removal. */
export function normalize(text: string): string {
  return text
    .replace(/[\u200c\u200f\u200e]/g, ' ')
    .replace(/[يى]/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/أ|إ|آ/g, 'ا')
    .replace(/ؤ/g, 'و')
    .replace(/ة/g, 'ه')
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

function tokenize(text: string): string[] {
  return normalize(text)
    .split(' ')
    .map((t) => t.replace(/(ها|های|هایم|شان|مان|ات|تر|ترین)$/, ''))
    .filter((t) => t.length > 1 && !STOPWORDS.has(t));
}

export interface LocalAnswer {
  text: string;
  topics: KnowledgeTopic[];
  confidence: number;
  source: 'offline';
}

/** Score-based retrieval over the offline knowledge base. */
export function answerLocal(query: string): LocalAnswer {
  const tokens = tokenize(query);
  const scored = KNOWLEDGE.map((topic) => {
    const hay = normalize(`${topic.title} ${topic.keywords.join(' ')} ${topic.body}`);
    let score = 0;
    for (const t of tokens) {
      const w = t.length <= 3 ? 1 : 2;
      if (hay.includes(t)) score += w;
      for (const k of topic.keywords) if (normalize(k).includes(t)) score += 1.5;
    }
    return { topic, score };
  })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score);

  const top = scored.slice(0, 3);
  const maxScore = scored[0]?.score ?? 0;
  const confidence = maxScore === 0 ? 0 : Math.min(1, maxScore / (tokens.length * 2 + 3));

  if (!top.length) {
    return {
      text:
        'برای این پرسش، منبع آفلاین من پاسخ مستقیمی ندارد. می‌توانید جزئیات فنی بیشتری (نوع عضو، ابعاد، بار وارده، نوع خاک) بفرمایید تا دقیق‌تر راهنمایی کنم. همچنین می‌توانید کلید Groq را در تنظیمات وارد کنید تا از مدل زبانی آنلاین استفاده شود.',
      topics: [],
      confidence: 0,
      source: 'offline',
    };
  }

  const parts = top.map((x, i) => `${i + 1}) ${x.topic.title}\n${x.topic.body}`);
  return {
    text: `${parts.join('\n\n')}\n\nمراجع: ${top.flatMap((x) => x.topic.refs).filter((v, i, a) => a.indexOf(v) === i).join(' | ')}`,
    topics: top.map((x) => x.topic),
    confidence,
    source: 'offline',
  };
}

/* --------------------------------------------------------------- Groq API -- */

export interface GroqAnswer {
  text: string;
  model: string;
  source: 'groq';
}

const GROQ_URL = 'https://api.groq.com/openai/v1/chat/completions';
const GROQ_MODEL = 'llama-3.3-70b-versatile';

export interface ChatMessage {
  role: 'system' | 'user' | 'assistant';
  content: string;
}

export async function answerGroq(
  query: string,
  history: ChatMessage[],
  apiKey: string,
): Promise<GroqAnswer> {
  const system: ChatMessage = {
    role: 'system',
    content:
      'تو مشاور ارشد مهندسی عمران هستی. بر اساس مبحث ششم، هفتم و نهم مقررات ملی ساختمان ایران و آیین‌نامه ۲۸۰۰ پاسخ بده. پاسخ را فارسی، دقیق، با واحدها و روابط مهندسی بنویس. اگر داده کافی نیست، سؤالات لازم را بپرس. از حدس‌های بدون مرجع پرهیز کن.',
  };
  const res = await fetch(GROQ_URL, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${apiKey}` },
    body: JSON.stringify({
      model: GROQ_MODEL,
      temperature: 0.35,
      max_tokens: 900,
      messages: [system, ...history.slice(-8), { role: 'user', content: query }],
    }),
  });
  if (!res.ok) {
    const detail = await res.text().catch(() => '');
    throw new Error(`خطای Groq (${res.status}): ${detail.slice(0, 160)}`);
  }
  const data = (await res.json()) as { choices?: { message?: { content?: string } }[] };
  const text = data.choices?.[0]?.message?.content?.trim();
  if (!text) throw new Error('پاسخ خالی از Groq');
  return { text, model: GROQ_MODEL, source: 'groq' };
}

